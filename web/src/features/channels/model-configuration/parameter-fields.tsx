import { useId } from 'react'
import { useTranslation } from 'react-i18next'

import { Button } from '@/components/ui/button'
import { Checkbox } from '@/components/ui/checkbox'
import {
  Field,
  FieldGroup,
  FieldLabel,
  FieldDescription,
} from '@/components/ui/field'
import { Input } from '@/components/ui/input'
import {
  Select,
  SelectContent,
  SelectGroup,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select'
import { Textarea } from '@/components/ui/textarea'

import { AllowedValueFields } from './allowed-value-fields'
import {
  acceptsStringArrayItems,
  parameterKeys,
  requiredParameter,
  DURATION_ALIASES,
  numericParameter,
} from './configuration'
import { PARAMETER_LABELS } from './parameter-labels'
import { ReferenceFields } from './reference-fields'
import type { Mode } from './types'
import { relevantParameter } from './workflow'

export function ParameterFields(props: {
  mode: Mode
  documentedNames?: Record<string, string>
  onChange: (mode: Mode) => void
  advanced?: boolean
  contractMaximums?: Record<string, number>
  referenceValues?: boolean
  capability?: string
  overrides?: import('./types').Binding
  allowExclusion?: boolean
  onClearOverride?: (field: string) => void
}) {
  const { t } = useTranslation()
  const prefix = useId()
  const keys = parameterKeys({ ...props.mode, mapping: {} }).filter(
    (key) =>
      (!props.capability ||
        relevantParameter(
          key,
          props.capability,
          props.mode.parameters?.[key]
        )) &&
      (props.advanced ||
        props.mode.parameters?.[key]?.definition?.['x-channel-parameter'] ||
        PARAMETER_LABELS[key] ||
        requiredParameter(props.mode, key) ||
        key === 'model' ||
        key === 'client_request_id')
  )
  function update(key: string, value: unknown): void {
    const next = structuredClone(props.mode)
    if (DURATION_ALIASES.includes(key)) {
      for (const alias of DURATION_ALIASES) delete next.input[alias]
    }
    if (value === undefined) delete next.input[key]
    else next.input[key] = value
    props.onChange(next)
  }
  return (
    <FieldGroup className='grid gap-4 md:grid-cols-2'>
      {keys.map((key) => {
        const parameter = props.mode.parameters?.[key],
          value =
            props.mode.input[key] ??
            (DURATION_ALIASES.includes(key)
              ? DURATION_ALIASES.map((alias) => props.mode.input[alias]).find(
                  (item) => item !== undefined
                )
              : undefined),
          id = `${prefix}-${key}`
        const membership = parameter?.definition?.['x-channel-parameter'] as
          | Record<string, unknown>
          | undefined
        const vendorFields = membership?.vendorFields
        const documentedName =
          props.documentedNames?.[key] ??
          (Array.isArray(vendorFields) && vendorFields.length === 1
            ? String(vendorFields[0])
            : undefined)
        const type =
          parameter?.type ?? (Array.isArray(value) ? 'array' : typeof value)
        const readOnly =
          !props.referenceValues &&
          (requiredParameter(props.mode, key) ||
            parameter?.definition?.['x-scope-conflict'] === true ||
            (
              parameter?.definition?.['x-channel-parameter'] as
                | Record<string, unknown>
                | undefined
            )?.workflowManaged === true ||
            key === 'model' ||
            key === 'client_request_id')
        if (readOnly) {
          let message =
            'Required by the document; inherited automatically and supplied by the caller at runtime'
          if (key === 'model' || key === 'client_request_id') {
            message = 'Generated by the gateway; do not enter it manually'
          }
          if (parameter?.definition?.['x-scope-conflict'] === true) {
            message =
              'Rules differ between selected functions; choose a function to configure them separately'
          }
          if (
            (
              parameter?.definition?.['x-channel-parameter'] as
                | Record<string, unknown>
                | undefined
            )?.workflowManaged === true
          ) {
            message = 'Managed by the existing task workflow'
          }
          return (
            <Field key={key} data-testid={`required-parameter-${key}`}>
              <FieldLabel>
                {t(PARAMETER_LABELS[key] ?? key)}{' '}
                <code>{documentedName ?? key}</code>
              </FieldLabel>
              <FieldDescription>{t(message)}</FieldDescription>
              <details>
                <summary>{t('View document rules')}</summary>
                <pre className='text-muted-foreground text-xs whitespace-pre-wrap'>
                  {JSON.stringify(parameter, null, 2)}
                </pre>
              </details>
            </Field>
          )
        }
        let control
        const durationOptions = parameter?.definition?.[
          'x-channel-parameter'
        ] as { documentedEnum?: unknown[] } | undefined
        const unlimited =
          parameter?.definition?.['x-business-allowed-values'] === 'unlimited'
        const durationEnum =
          !unlimited &&
          key === 'seconds' &&
          durationOptions?.documentedEnum?.length
        const businessRule =
          parameter?.definition?.['x-business-allowed-values']
        let documentedOptions = businessRule ? undefined : parameter?.enum
        if (!unlimited && Array.isArray(parameter?.definition?.enum)) {
          documentedOptions = parameter.definition.enum
        }
        if (durationEnum) {
          documentedOptions = durationOptions?.documentedEnum?.map(Number)
        }
        const configuredOptions = durationEnum
          ? parameter?.enum?.filter((item) => typeof item === 'number')
          : parameter?.enum
        if (documentedOptions?.length) {
          control = (
            <div className='space-y-3'>
              <p className='text-muted-foreground text-xs'>
                {t('Allowed values (choose several)')}
              </p>
              <div className='flex flex-wrap gap-3'>
                {documentedOptions.map((option) => (
                  <label
                    key={JSON.stringify(option)}
                    className='flex items-center gap-2 text-sm'
                  >
                    <Checkbox
                      aria-label={`${key}: ${String(option)}`}
                      checked={
                        configuredOptions?.some(
                          (item) =>
                            JSON.stringify(item) === JSON.stringify(option)
                        ) ?? true
                      }
                      onCheckedChange={(checked) => {
                        const next = structuredClone(props.mode)
                        const current = next.parameters?.[key]
                        if (!current) return
                        const options = configuredOptions ?? documentedOptions
                        const allowed = checked
                          ? [...options, option]
                          : options.filter(
                              (item) =>
                                JSON.stringify(item) !== JSON.stringify(option)
                            )
                        if (!allowed.length) return
                        if (!durationEnum) {
                          current.definition = {
                            ...current.definition,
                            enum: documentedOptions,
                          }
                        }
                        current.enum = [
                          ...new Map(
                            allowed.map((item) => [JSON.stringify(item), item])
                          ).values(),
                        ]
                        if (durationEnum) {
                          current.enum = current.enum.flatMap((item) => [
                            item,
                            String(item),
                          ])
                        }
                        if (
                          Object.hasOwn(next.input, key) &&
                          !current.enum.some(
                            (item) =>
                              JSON.stringify(item) ===
                              JSON.stringify(next.input[key])
                          )
                        ) {
                          delete next.input[key]
                        }
                        if (
                          current.default !== undefined &&
                          !current.enum.some(
                            (item) =>
                              JSON.stringify(item) ===
                              JSON.stringify(current.default)
                          )
                        ) {
                          delete current.default
                        }
                        props.onChange(next)
                      }}
                    />
                    {String(option)}
                  </label>
                ))}
              </div>
              <p className='text-muted-foreground text-xs'>
                {t('Default value (optional)')}
              </p>
              <Select
                value={
                  value === undefined ? '__unset__' : JSON.stringify(value)
                }
                onValueChange={(next) =>
                  update(
                    key,
                    next === '__unset__' ? undefined : JSON.parse(String(next))
                  )
                }
              >
                <SelectTrigger id={id}>
                  <SelectValue>
                    {value === undefined ? t('Not specified') : String(value)}
                  </SelectValue>
                </SelectTrigger>
                <SelectContent>
                  <SelectGroup>
                    <SelectItem value='__unset__'>
                      {t('Not specified')}
                    </SelectItem>
                    {(configuredOptions ?? documentedOptions).map((option) => (
                      <SelectItem
                        key={JSON.stringify(option)}
                        value={JSON.stringify(option)}
                      >
                        {String(option)}
                      </SelectItem>
                    ))}
                  </SelectGroup>
                </SelectContent>
              </Select>
            </div>
          )
        } else if (
          type === 'array' &&
          /image|video|audio|reference/.test(key) &&
          !key.endsWith('_durations')
        ) {
          control = props.referenceValues ? (
            <ReferenceFields
              name={t(PARAMETER_LABELS[key] ?? key)}
              value={value}
              parameter={parameter}
              onChange={(value) => update(key, value)}
            />
          ) : (
            <div className='space-y-2 text-sm'>
              <p>
                {t(
                  'Optional caller parameter; no reference is required just because this capability is enabled'
                )}
              </p>
              <label className='block space-y-1'>
                <span>业务允许的最多素材数</span>
                <Input
                  type='number'
                  aria-label={`${t(PARAMETER_LABELS[key] ?? key)}：业务允许的最多素材数`}
                  min={1}
                  max={
                    props.contractMaximums?.[key] ??
                    (Number(parameter?.definition?.maxItems) || undefined)
                  }
                  value={
                    typeof parameter?.definition?.maxItems === 'number'
                      ? parameter.definition.maxItems
                      : ''
                  }
                  placeholder='留空继承文档限制'
                  onChange={(event) => {
                    const text = event.target.value
                    const count = Number(text)
                    const maximum = props.contractMaximums?.[key]
                    if (
                      text !== '' &&
                      (!Number.isInteger(count) ||
                        count < 1 ||
                        (maximum !== undefined && count > maximum))
                    ) {
                      return
                    }
                    const next = structuredClone(props.mode)
                    const definition = { ...parameter?.definition }
                    if (text === '') delete definition.maxItems
                    else definition.maxItems = count
                    next.parameters = {
                      ...next.parameters,
                      [key]: { ...parameter, definition },
                    }
                    props.onChange(next)
                  }}
                />
              </label>
              <p className='text-muted-foreground'>
                文档上限：
                {String(
                  props.contractMaximums?.[key] ??
                    parameter?.definition?.maxItems ??
                    t('Not confirmed')
                )}
                ；可以不传素材。素材结构和上游组合约束保持有效。
              </p>
              <p className='text-muted-foreground'>
                {t(
                  'Fill sample addresses in the no-charge input preview below. They are not saved as defaults.'
                )}
              </p>
            </div>
          )
        } else if (type === 'boolean') {
          control = (
            <Checkbox
              id={id}
              checked={value === true}
              onCheckedChange={(checked) => update(key, checked)}
            />
          )
        } else if (
          type === 'array' &&
          acceptsStringArrayItems(parameter) &&
          (value === undefined ||
            (Array.isArray(value) &&
              value.every((item) => typeof item === 'string')))
        ) {
          control = (
            <Textarea
              id={id}
              value={Array.isArray(value) ? value.join('\n') : ''}
              placeholder={t('One address per line')}
              onChange={(event) =>
                update(
                  key,
                  event.target.value
                    .split(/\r?\n/)
                    .map((item) => item.trim())
                    .filter(Boolean)
                )
              }
            />
          )
        } else if (type === 'object' || type === 'array') {
          control = (
            <Textarea
              id={id}
              readOnly
              value={value === undefined ? '' : JSON.stringify(value, null, 2)}
              aria-label={t('Edit complex values in the JSON editor')}
            />
          )
        } else if (key === 'prompt') {
          control = (
            <Textarea
              id={id}
              value={typeof value === 'string' ? value : ''}
              onChange={(event) => update(key, event.target.value)}
            />
          )
        } else if (
          type === 'number' ||
          type === 'integer' ||
          numericParameter(parameter)
        ) {
          control = (
            <Input
              id={id}
              type='number'
              step={type === 'number' ? 'any' : 1}
              min={unlimited ? undefined : parameter?.minimum}
              max={unlimited ? undefined : parameter?.maximum}
              value={
                typeof value === 'number' ||
                (typeof value === 'string' && /^\d+$/.test(value))
                  ? value
                  : ''
              }
              onChange={(event) =>
                update(
                  key,
                  event.target.value === ''
                    ? undefined
                    : Number(event.target.value)
                )
              }
            />
          )
        } else {
          control = (
            <Input
              id={id}
              value={value === undefined ? '' : String(value)}
              onChange={(event) => update(key, event.target.value)}
            />
          )
        }
        const included = props.mode.mapping?.[key] !== '@ignore'
        return (
          <Field key={key}>
            <div className='flex items-center justify-between gap-2'>
              <FieldLabel htmlFor={id}>
                {t(PARAMETER_LABELS[key] ?? key)}
                {documentedName && (
                  <code className='text-muted-foreground ml-2 text-xs'>
                    {documentedName}
                  </code>
                )}
                {props.overrides && (
                  <span className='text-muted-foreground ml-2 text-xs'>
                    {t(
                      Object.hasOwn(props.overrides.input ?? {}, key) ||
                        Object.hasOwn(props.overrides.parameters ?? {}, key) ||
                        Object.hasOwn(props.overrides.mapping ?? {}, key)
                        ? 'Individually set'
                        : 'Inherited'
                    )}
                  </span>
                )}
                {parameter?.required ? ' *' : ''}
              </FieldLabel>
              {(props.overrides
                ? Object.hasOwn(props.overrides.input ?? {}, key) ||
                  Object.hasOwn(props.overrides.parameters ?? {}, key) ||
                  Object.hasOwn(props.overrides.mapping ?? {}, key)
                : Object.hasOwn(props.mode.input, key)) && (
                <Button
                  size='sm'
                  variant='ghost'
                  onClick={() =>
                    props.onClearOverride
                      ? props.onClearOverride(key)
                      : update(key, undefined)
                  }
                >
                  {t(props.overrides ? 'Restore inheritance' : 'Use default')}
                </Button>
              )}
            </div>
            {props.allowExclusion && (
              <label className='flex items-center gap-2 text-sm'>
                <Checkbox
                  aria-label={`${t('Include parameter')}: ${key}`}
                  checked={included}
                  onCheckedChange={(checked) => {
                    const next = structuredClone(props.mode)
                    next.mapping = {
                      ...next.mapping,
                      [key]: checked ? key : '@ignore',
                    }
                    props.onChange(next)
                  }}
                />
                {t(included ? 'Included' : 'Excluded for this configuration')}
              </label>
            )}
            <fieldset disabled={!included} className='contents'>
              {parameter &&
                key !== 'prompt' &&
                (numericParameter(parameter) || type === 'string') && (
                  <AllowedValueFields
                    field={key}
                    documentedChoices={
                      (parameter.definition?.enum as unknown[] | undefined) ??
                      (durationOptions?.documentedEnum?.length
                        ? durationOptions.documentedEnum.flatMap((value) => [
                            Number(value),
                            String(value),
                          ])
                        : undefined)
                    }
                    name={documentedName ?? key}
                    mode={props.mode}
                    onChange={props.onChange}
                  />
                )}
              {!documentedOptions?.length &&
                key !== 'prompt' &&
                (numericParameter(parameter) || type === 'string') && (
                  <p className='text-muted-foreground text-xs'>
                    {t('Default value (optional)')} ·{' '}
                    {t(
                      'One value only; leave blank to omit. Allowed values and ranges are configured separately.'
                    )}
                  </p>
                )}
              {control}
            </fieldset>
            {Boolean(membership) && typeof membership === 'object' && (
              <FieldDescription>
                {t(
                  (membership as Record<string, unknown>).status ===
                    'documented' &&
                    (membership as Record<string, unknown>).requiredStatus !==
                      'manual-verification-required'
                    ? 'Documented parameter'
                    : 'Document details need confirmation'
                )}
                {typeof (membership as Record<string, unknown>).condition ===
                  'string' &&
                  ` · ${(membership as Record<string, unknown>).condition}`}
              </FieldDescription>
            )}
            {(parameter?.default !== undefined ||
              parameter?.definition?.documentedDefault !== undefined) && (
              <FieldDescription>
                {t('Document default')}:{' '}
                {String(
                  parameter?.default ?? parameter?.definition?.documentedDefault
                )}
              </FieldDescription>
            )}
            {props.advanced && parameter?.description && (
              <FieldDescription>{parameter.description}</FieldDescription>
            )}
          </Field>
        )
      })}
    </FieldGroup>
  )
}
